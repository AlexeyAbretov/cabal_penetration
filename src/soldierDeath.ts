/**
 * Ролик нарисован лицом на северо-восток.
 * Угол Phaser по часовой стрелке: 0 смотрит вправо.
 * Сюда передаётся сторона, куда смотрел, и возвращается противоположная.
 * Север падает на запад, тем же углом, что взгляд на восток.
 */
export function deathAngle(look: -1 | 0 | 1): number {
  if (look < 0) return 5;
  return -5;
}
