/**
 * Дерево на поле.
 * Очередь колет, граната валит сразу. Бонус берётся из списка картинки.
 * Ствол после слома остаётся: пень на месте ствола, крона лежит рядом.
 * Сторона падения зеркалится. У живого ещё листва и куча по ширине кроны.
 */
export type TreeMark = {
  /** Середина ствола, доля ширины поля. */
  x: number;
  /** Подошва, доля опорного поля вниз от горизонта. */
  y: number;
  /** Высота каркаса в пикселях листа, до сжатия маленького окна. */
  h: number;
  /** Живое: листва и куча листьев. Сломанный лист тот же, что у сухого. */
  live: boolean;
};
