/**
 * Бочка на поле.
 * Ломается щепой и оставляет нижнюю половину. Бонус берётся из списка картинки.
 */
export type BarrelMark = {
  /** Середина, доля ширины поля. */
  x: number;
  /**
   * Без horizon: середина, 0 дальний край поля, 1 у дорожки.
   * С horizon: подошва, доля опорного поля вниз от горизонта, как низ дома.
   */
  y: number;
  /** Сдвиг середины от x. Пиксели листа, до масштаба глубины. */
  dx?: number;
  /** Подошва стоит на линии горизонта, рядом с домом, на любом окне. */
  horizon?: boolean;
  /** Очки в момент слома. Нет — номинал бочки. */
  score?: number;
};
